"""Generate the browser's 4x4_50 data bits from OpenCV (requires cv2.aruco)."""
from pathlib import Path
import cv2
aruco = cv2.aruco
D = (aruco.getPredefinedDictionary(aruco.DICT_4X4_50) if hasattr(aruco, 'getPredefinedDictionary')
     else aruco.Dictionary_get(aruco.DICT_4X4_50))
patterns = []
for i in range(50):
    img = (aruco.generateImageMarker(D, i, 6, borderBits=1) if hasattr(aruco, 'generateImageMarker')
           else aruco.drawMarker(D, i, 6, borderBits=1))
    patterns.append(''.join('1' if img[y, x] == 0 else '0' for y in range(1, 5) for x in range(1, 5)))
output = Path(__file__).resolve().parents[1] / 'src/aruco_4x4_50.ts'
output.write_text('// OpenCV DICT_4X4_50, row-major black=1 data bits; generated by tools/generate_aruco_dictionary.py.\nexport const ARUCO_4X4_50 = [\n' + ''.join(f'  "{pattern}",\n' for pattern in patterns) + '] as const;\n', encoding='utf-8')
